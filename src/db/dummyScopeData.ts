/**
 * Builds all 51 plans corresponding to the 51 trades (status TRIGGERED).
 */
export function buildTriggeredPlans(): Plan[] {
  return TEMPLATES.map((tmpl) => ({
    id: tmpl.planId,
    accountId: tmpl.accountId,
    phaseId: tmpl.phaseId,
    symbol: tmpl.symbol,
    direction: tmpl.direction,
    plannedEntry: tmpl.plannedEntry,
    sl: tmpl.sl,
    tp: tmpl.tp,
    positionSize: tmpl.actualPositionSize,
    risk: Math.round(Math.abs(tmpl.plannedEntry - tmpl.sl) * tmpl.actualPositionSize * 100),
    setupId: tmpl.setupId,
    timeframe: '15m',
    marketBias: tmpl.direction === 'BUY' ? 'BULLISH' : 'BEARISH',
    entryReason: 'Triggered execution setup based on predefined trading plan',
    confidence: 4,
    status: 'TRIGGERED',
    createdAt: tmpl.entryTime,
    updatedAt: tmpl.completedTime || tmpl.entryTime,
  }));
}

/**
 * Builds all 51 trade entities (50 COMPLETED + 1 ACTIVE).
 */
export function buildTrades(): Trade[] {
  return TEMPLATES.map((tmpl) => ({
    id: tmpl.id,
    planId: tmpl.planId,
    accountId: tmpl.accountId,
    phaseId: tmpl.phaseId,
    actualEntry: tmpl.actualEntry,
    actualEntryTime: tmpl.entryTime,
    actualPositionSize: tmpl.actualPositionSize,
    status: tmpl.status,
    realizedPnL: tmpl.pnl,
    result: tmpl.result,
    completedAt: tmpl.completedTime,
    createdAt: tmpl.entryTime,
    updatedAt: tmpl.completedTime || tmpl.entryTime,
  }));
}

/**
 * Builds exits for all completed trades (50 exits).
 */
export function buildExits(): Exit[] {
  return TEMPLATES.filter((t) => t.status === 'COMPLETED' && t.completedTime && t.pnl !== null).map((tmpl) => ({
    id: `dummy-exit-${tmpl.id.replace('dummy-trade-', '')}`,
    tradeId: tmpl.id,
    executedAt: tmpl.completedTime!,
    price: tmpl.exitPrice ?? tmpl.tp,
    closedSize: tmpl.actualPositionSize,
    exitType: tmpl.exitType || (tmpl.pnl! > 0 ? 'FULL_TP' : tmpl.pnl! < 0 ? 'FULL_SL' : 'OTHER'),
    realizedPnL: tmpl.pnl!,
    reason: `Automated plan execution exit: ${tmpl.exitType || 'Market exit'}`,
  }));
}

/**
 * Builds reviews for completed trades.
 */
export function buildReviews(): TradeReview[] {
  const reviews: TradeReview[] = [];
  TEMPLATES.forEach((tmpl) => {
    if (tmpl.review && tmpl.completedTime) {
      reviews.push({
        id: `dummy-rev-${tmpl.id.replace('dummy-trade-', '')}`,
        tradeId: tmpl.id,
        followedPlan: tmpl.review.followedPlan,
        whatHappened: tmpl.review.whatHappened,
        lessonLearned: tmpl.review.lessonLearned,
        createdAt: tmpl.completedTime,
      });
    }
  });
  return reviews;
}

/**
 * Seeds the complete, realistic Account Scope test dataset.
 * Safe and idempotent: Uses stable IDs and bulkPut to reconcile in-place without duplicating.
 */
export async function seedAccountScopeTestData(): Promise<{
  accountsCount: number;
  tradesCount: number;
  plansCount: number;
  exitsCount: number;
}> {
  const triggeredPlans = buildTriggeredPlans();
  const allPlans = [...triggeredPlans, ...DUMMY_ADDITIONAL_PLANS];
  const allTrades = buildTrades();
  const allExits = buildExits();
  const allReviews = buildReviews();

  await db.transaction(
    'rw',
    [
      db.accounts,
      db.accountPhases,
      db.propFirmRules,
      db.setups,
      db.transactions,
      db.plans,
      db.trades,
      db.exits,
      db.reviews,
    ],
    async () => {
      // 1. Setups
      await db.setups.bulkPut(DUMMY_SETUPS);
      // 2. Accounts
      await db.accounts.bulkPut(DUMMY_ACCOUNTS);
      // 3. Phases
      await db.accountPhases.bulkPut(DUMMY_PHASES);
      // 4. Rules
      await db.propFirmRules.bulkPut(DUMMY_PROP_RULES);
      // 5. Transactions
      await db.transactions.bulkPut(DUMMY_TRANSACTIONS);
      // 6. Plans
      await db.plans.bulkPut(allPlans);
      // 7. Trades
      await db.trades.bulkPut(allTrades);
      // 8. Exits
      await db.exits.bulkPut(allExits);
      // 9. Reviews
      if (allReviews.length > 0) {
        await db.reviews.bulkPut(allReviews);
      }
    }
  );

  return {
    accountsCount: DUMMY_ACCOUNTS.length,
    tradesCount: allTrades.length,
    plansCount: allPlans.length,
    exitsCount: allExits.length,
  };
}

/**
 * Surgically purges ONLY test records with prefix 'dummy-'.
 * 100% reversible: strictly never deletes or touches user-created data.
 */
export async function purgeAccountScopeTestData(): Promise<{
  deletedCount: number;
}> {
  let deletedCount = 0;

  await db.transaction(
    'rw',
    [
      db.accounts,
      db.accountPhases,
      db.propFirmRules,
      db.setups,
      db.transactions,
      db.plans,
      db.trades,
      db.exits,
      db.reviews,
    ],
    async () => {
      const isDummy = (id: string) => id.startsWith('dummy-');

      const dummyAccs = (await db.accounts.toArray()).filter((a) => isDummy(a.id));
      const dummyPhases = (await db.accountPhases.toArray()).filter((p) => isDummy(p.id));
      const dummyRules = (await db.propFirmRules.toArray()).filter((r) => isDummy(r.id));
      const dummySetups = (await db.setups.toArray()).filter((s) => isDummy(s.id));
      const dummyTxs = (await db.transactions.toArray()).filter((t) => isDummy(t.id));
      const dummyPlans = (await db.plans.toArray()).filter((p) => isDummy(p.id));
      const dummyTrades = (await db.trades.toArray()).filter((t) => isDummy(t.id));
      const dummyExits = (await db.exits.toArray()).filter((e) => isDummy(e.id));
      const dummyReviews = (await db.reviews.toArray()).filter((r) => isDummy(r.id));

      await Promise.all([
        db.accounts.bulkDelete(dummyAccs.map((a) => a.id)),
        db.accountPhases.bulkDelete(dummyPhases.map((p) => p.id)),
        db.propFirmRules.bulkDelete(dummyRules.map((r) => r.id)),
        db.setups.bulkDelete(dummySetups.map((s) => s.id)),
        db.transactions.bulkDelete(dummyTxs.map((t) => t.id)),
        db.plans.bulkDelete(dummyPlans.map((p) => p.id)),
        db.trades.bulkDelete(dummyTrades.map((t) => t.id)),
        db.exits.bulkDelete(dummyExits.map((e) => e.id)),
        db.reviews.bulkDelete(dummyReviews.map((r) => r.id)),
      ]);

      deletedCount =
        dummyAccs.length +
        dummyPhases.length +
        dummyRules.length +
        dummySetups.length +
        dummyTxs.length +
        dummyPlans.length +
        dummyTrades.length +
        dummyExits.length +
        dummyReviews.length;
    }
  );

  return { deletedCount };
}

